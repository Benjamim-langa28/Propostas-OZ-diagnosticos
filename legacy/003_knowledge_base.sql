-- OZ Intelligent Proposal — base de conhecimento (patologias, ensaios, soluções, etc.)
-- Correr depois de 001_schema.sql. Idempotente: pode ser executado novamente para atualizar os dados.
-- Os códigos são uma proposta interna; not_in_manual = true marca o que não consta do manual base.
-- Conteúdo técnico (causas, ensaios, severidade, soluções) a validar por um engenheiro da OZ.

create table if not exists kb_construction_types (code text primary key, category text not null, name text not null, notes text, not_in_manual boolean not null default false);
create table if not exists kb_elements (code text primary key, name text not null, not_in_manual boolean not null default false);
create table if not exists kb_causes (code text primary key, name text not null, not_in_manual boolean not null default false);
create table if not exists kb_tests (code text primary key, name text not null, test_group text, service_id text references services(service_id), not_in_manual boolean not null default false);
create table if not exists kb_solutions (code text primary key, name text not null, not_in_manual boolean not null default false);
create table if not exists kb_severity (level int primary key check (level between 1 and 4), name text not null, meaning text, action text);
create table if not exists kb_pathology_groups (code text primary key, name text not null);
create table if not exists kb_pathologies (
  code text primary key, group_code text not null references kb_pathology_groups(code), name text not null,
  sev_min int not null references kb_severity(level), sev_max int not null references kb_severity(level),
  not_in_manual boolean not null default false, active boolean not null default true);
create table if not exists kb_pathology_causes (pathology_code text references kb_pathologies(code) on delete cascade, cause_code text references kb_causes(code), primary key (pathology_code, cause_code));
create table if not exists kb_pathology_tests (pathology_code text references kb_pathologies(code) on delete cascade, test_code text references kb_tests(code), primary key (pathology_code, test_code));
create table if not exists kb_pathology_solutions (pathology_code text references kb_pathologies(code) on delete cascade, solution_code text references kb_solutions(code), primary key (pathology_code, solution_code));
create index if not exists kb_pc_cause on kb_pathology_causes(cause_code);
create index if not exists kb_pt_test on kb_pathology_tests(test_code);
create index if not exists kb_ps_sol on kb_pathology_solutions(solution_code);
create table if not exists kb_services (code text primary key, name text not null, unit text, not_in_manual boolean not null default false);
create table if not exists kb_client_info_items (code text primary key, name text not null, not_in_manual boolean not null default false);
create table if not exists kb_report_sections (code text primary key, name text not null, content text, not_in_manual boolean not null default false);
create table if not exists kb_equipment (code text primary key, name text not null, items text, not_in_manual boolean not null default false);
create table if not exists kb_materials (code text primary key, name text not null, items text);
create table if not exists kb_reference_notes (code text primary key, title text not null, content text, not_in_manual boolean not null default false);

