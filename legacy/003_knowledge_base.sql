-- Vista de leitura: patologia com causas, ensaios e soluções
create or replace view kb_pathologies_full as
select p.code, g.name as group_name, p.name, p.sev_min, p.sev_max, p.not_in_manual,
  (select array_agg(cause_code order by cause_code) from kb_pathology_causes where pathology_code = p.code) as causes,
  (select array_agg(test_code order by test_code) from kb_pathology_tests where pathology_code = p.code) as tests,
  (select array_agg(solution_code order by solution_code) from kb_pathology_solutions where pathology_code = p.code) as solutions
from kb_pathologies p join kb_pathology_groups g on g.code = p.group_code where p.active;

-- Segurança: leitura para utilizadores autenticados; escrita para ADMIN, MANAGER e ENGINEER (my_role() vem do 001)
do $$ declare t text; begin
  foreach t in array array['kb_construction_types','kb_elements','kb_causes','kb_tests','kb_solutions','kb_severity','kb_pathology_groups','kb_pathologies','kb_pathology_causes','kb_pathology_tests','kb_pathology_solutions','kb_services','kb_client_info_items','kb_report_sections','kb_equipment','kb_materials','kb_reference_notes'] loop
    execute format('alter table %I enable row level security', t);
    execute format('drop policy if exists "kb_ler" on %I', t);
    execute format('create policy "kb_ler" on %I for select using (auth.uid() is not null)', t);
    execute format('drop policy if exists "kb_escrever" on %I', t);
    execute format('create policy "kb_escrever" on %I for all using (my_role() in (''ADMIN'',''MANAGER'',''ENGINEER'')) with check (my_role() in (''ADMIN'',''MANAGER'',''ENGINEER''))', t);
  end loop; end $$;
